#!/usr/bin/env node
/**
 * Regenerates scripts/p5-globals.json: the names p5.js global mode (plus
 * p5.sound) defines on `window`, used by scripts/lint.js as allowed globals
 * when ESLint checks the concatenated game bundle.
 *
 * How: loads the exact p5 / p5.sound <script> URLs pinned in src/index.html
 * into a blank headless page, snapshots window's own property names, lets p5
 * start in global mode (a stub `setup` triggers it), then records every name
 * that appeared. That is precisely the set the game can reference as bare
 * identifiers, with no hand-maintained list and no extra npm dependency.
 *
 * Run after changing the p5 CDN pins (scripts/lint.js fails until you do):
 *   npm run lint:p5-globals
 *
 * Needs network access to cdnjs and a Chromium-based browser: system Brave by
 * default, or PLAYTEST_BROWSER_PATH=/path/to/browser (same as the playtest).
 */
const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.join(__dirname, '..');
const INDEX_HTML = path.join(REPO_ROOT, 'src', 'index.html');
const OUTPUT_FILE = path.join(__dirname, 'p5-globals.json');
const DEFAULT_BRAVE_PATH = '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser';
const BROWSER_PATH = process.env.PLAYTEST_BROWSER_PATH || DEFAULT_BRAVE_PATH;
const PROBE_URL = 'http://127.0.0.1/p5-globals-probe.html';

/**
 * Returns the external p5 library <script> URLs from src/index.html, in order.
 * Shared with scripts/lint.js so a CDN pin change is detected as stale globals.
 * @param {string} html
 * @returns {string[]}
 */
function readP5ScriptUrls(html) {
    const urls = [];
    const scriptSrcRegex = /<script\s+src="(https:\/\/[^"]*\/p5\.js\/[^"]+)"/g;
    let match;
    while ((match = scriptSrcRegex.exec(html)) !== null) {
        urls.push(match[1]);
    }
    return urls;
}

async function collectGlobals(scriptUrls) {
    const { chromium } = require('playwright');
    const browser = await chromium.launch({ executablePath: BROWSER_PATH, headless: true });
    try {
        const page = await browser.newPage();
        const scriptTags = scriptUrls
            .map((url) => `<script src="${url}"></script>`)
            .join('\n');
        // The inline script runs before the libraries load, so `before` is the
        // plain browser global set; `setup` is a p5 lifecycle hook that tells p5
        // to start in global mode on window load. The page is fulfilled on a
        // routed loopback URL (nothing listens there) because p5.sound needs
        // AudioWorklet, which only exists in a secure context (not about:blank).
        const html = `<!DOCTYPE html><html><head>
<script>
    window.__p5GlobalsBefore = Object.getOwnPropertyNames(window);
    window.__p5SetupRan = false;
    function setup() { window.__p5SetupRan = true; }
</script>
${scriptTags}
</head><body></body></html>`;
        const pageErrors = [];
        page.on('pageerror', (error) => pageErrors.push(error.message));
        await page.route(PROBE_URL, (route) => route.fulfill({ contentType: 'text/html', body: html }));
        await page.goto(PROBE_URL, { waitUntil: 'load', timeout: 60000 });
        if (pageErrors.length > 0) {
            throw new Error(`p5 failed to load: ${pageErrors.join('; ')}`);
        }
        await page.waitForFunction(() => window.__p5SetupRan === true, null, { timeout: 30000 });

        return await page.evaluate(() => {
            const before = new Set(window.__p5GlobalsBefore);
            const ignored = new Set(['__p5GlobalsBefore', '__p5SetupRan', 'setup']);
            return {
                version: window.p5 && window.p5.VERSION,
                names: Object.getOwnPropertyNames(window)
                    .filter((name) => !before.has(name) && !ignored.has(name))
                    // Drop internal non-identifier keys such as core-js's shared store.
                    .filter((name) => /^[A-Za-z_$][\w$]*$/.test(name))
                    .sort(),
            };
        });
    } finally {
        await browser.close();
    }
}

async function main() {
    if (!fs.existsSync(BROWSER_PATH)) {
        throw new Error(
            `Browser not found at: ${BROWSER_PATH}\n` +
            'Install Brave or set PLAYTEST_BROWSER_PATH to a Chromium-based browser binary.'
        );
    }

    const scriptUrls = readP5ScriptUrls(fs.readFileSync(INDEX_HTML, 'utf8'));
    if (scriptUrls.length === 0) {
        throw new Error('No p5.js <script src> found in src/index.html');
    }

    const { version, names } = await collectGlobals(scriptUrls);
    if (!names.includes('p5') || !names.includes('createCanvas') || !names.includes('loadSound')) {
        throw new Error(`Global capture looks incomplete (${names.length} names); refusing to write.`);
    }

    const output = {
        description: 'Generated by scripts/generate-p5-globals.js (npm run lint:p5-globals). Do not edit by hand.',
        p5Version: version,
        sources: scriptUrls,
        globals: names,
    };
    fs.writeFileSync(OUTPUT_FILE, JSON.stringify(output, null, 4) + '\n');
    console.log(`Wrote ${names.length} p5 ${version} globals to ${path.relative(REPO_ROOT, OUTPUT_FILE)}`);
}

module.exports = { readP5ScriptUrls };

if (require.main === module) {
    main().catch((error) => {
        console.error('Failed to generate p5 globals:', error && error.message ? error.message : error);
        process.exit(1);
    });
}
